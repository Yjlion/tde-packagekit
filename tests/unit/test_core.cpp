static int failures = 0;

#define CHECK(cond) do { if (!(cond)) { printf("FAIL %s:%d: %s\n", __FILE__, __LINE__, #cond); ++failures; } } while (0)
#define CHECK_EQ(a, b) do { if (TQString(a) != TQString(b)) { printf("FAIL %s:%d: '%s' != '%s'\n", __FILE__, __LINE__, TQString(a).latin1(), TQString(b).latin1()); ++failures; } } while (0)

/* Generated by checks at compile time: a mismatch stops the build. */
#define SAME(ours, theirs) static_assert(int(ours) == int(theirs), #ours)

