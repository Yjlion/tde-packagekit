static void testPackageId()
{
    PackageId p("hello;2.10-5;amd64;debian-stable-main");
    CHECK(p.isValid());
    CHECK_EQ(p.name(), "hello");
    CHECK_EQ(p.version(), "2.10-5");
    CHECK_EQ(p.arch(), "amd64");
    CHECK_EQ(p.origin(), "debian-stable-main");
    CHECK_EQ(p.display(), "hello 2.10-5 (amd64)");

    CHECK_EQ(PackageId("a;1;all;manual:debian-stable-main").origin(), "debian-stable-main");
    CHECK_EQ(PackageId("a;1;all;+auto:foo").origin(), "foo");
    CHECK(PackageId("a;1;all;installed").origin().isEmpty());

    /* A trailing empty data field is legal. */
    CHECK(PackageId("a;1;all;").isValid());
    CHECK(!PackageId("").isValid());
    CHECK(!PackageId("a;1;all").isValid());
    CHECK(!PackageId(";1;all;x").isValid());
    CHECK(!PackageId("a;1;all;x;y").isValid());
}

static void testBitfield()
{
    CHECK(Pk::bit(Pk::FilterNewest) == pk_bitfield_value(PK_FILTER_ENUM_NEWEST));
    CHECK(Pk::bit(Pk::TransactionFlagSimulate) == pk_bitfield_value(PK_TRANSACTION_FLAG_ENUM_SIMULATE));
    /* Filters live above bit 31, so the type must really be 64 bits wide. */
    CHECK(sizeof(Pk::Bitfield) == 8);
    CHECK(Pk::bit(40) == (TQ_UINT64(1) << 40));
}

static void testSeverity()
{
    CHECK(Pk::updateSeverityRank(Pk::InfoCritical) < Pk::updateSeverityRank(Pk::InfoSecurity));
    CHECK(Pk::updateSeverityRank(Pk::InfoSecurity) < Pk::updateSeverityRank(Pk::InfoImportant));
    CHECK(Pk::updateSeverityRank(Pk::InfoImportant) < Pk::updateSeverityRank(Pk::InfoBugfix));
    CHECK(Pk::updateSeverityRank(Pk::InfoBugfix) < Pk::updateSeverityRank(Pk::InfoNormal));
    CHECK(Pk::updateSeverityRank(Pk::InfoNormal) < Pk::updateSeverityRank(Pk::InfoLow));
    CHECK(Pk::infoIsInstalled(Pk::InfoInstalled));
    CHECK(!Pk::infoIsInstalled(Pk::InfoAvailable));
}

static void testGroups()
{
    /* Every group has a name PackageKit would accept. */
    for (uint g = Pk::GroupAccessibility; g < Pk::GroupLast; ++g) {
        CHECK(Pk::groupId(g) != "unknown");
        CHECK_EQ(Pk::groupId(g), pk_group_enum_to_string(PkGroupEnum(g)));
    }
}

int main()
{
    testPackageId();
    testBitfield();
    testSeverity();
    testGroups();
    printf(failures ? "%d failure(s)\n" : "all core tests passed\n", failures);
    return failures ? 1 : 0;
}
